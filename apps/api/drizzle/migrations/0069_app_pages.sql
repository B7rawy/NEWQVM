-- 0069_app_pages.sql — the sidebar stops being a hard-coded list and becomes data.
--
-- WHY. Three things were impossible while the menus lived in nav.tsx. A workspace with no workshop
-- linked still showed workshop pages. A page could not be shown to one job title and hidden from
-- another. And changing either meant a deploy. This table is the catalog; app_page_roles is who may
-- see each one; `module` is what switches a page on.
--
-- THE RULE. A page whose module is a counterparty family (workshop / vendor / service_provider /
-- internal) exists in a workspace ONLY while that workspace has an active link of that kind. Pages
-- with module='core' are always there. The pages that CREATE a counterparty are core on purpose —
-- gate "Add supplier / workshop" on already having one and a new workspace could never onboard its
-- first, which is exactly the empty workspace this change is meant to support.
--
-- SEEDED BY TRANSCRIPTION, NOT BY HAND. Every row below was generated by parsing nav.tsx, so the
-- catalog starts as precisely the menus that shipped before it — same labels, same order, same
-- groups, same admin-only gates. Nothing about anyone's sidebar changes on the day this lands; what
-- changes is that it can now be changed.

create table if not exists app_pages (
  key           text primary key,
  module        text not null check (module in ('core','workshop','vendor','service_provider','internal')),
  persona       text not null,
  path          text not null,
  label         text not null,
  icon          text not null,
  group_heading text not null,
  sort_order    integer not null,
  is_built      boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);--> statement-breakpoint

create table if not exists app_page_roles (
  page_key text not null references app_pages(key) on delete cascade,
  role     text not null,
  primary key (page_key, role)
);--> statement-breakpoint

create index if not exists app_pages_persona_idx on app_pages (persona, sort_order);--> statement-breakpoint

-- Global reference data, same shape as item_statuses: everyone reads, only platform staff writes.
alter table app_pages enable row level security;--> statement-breakpoint
alter table app_page_roles enable row level security;--> statement-breakpoint
drop policy if exists global_read on app_pages;--> statement-breakpoint
create policy global_read on app_pages for select using (true);--> statement-breakpoint
drop policy if exists global_write on app_pages;--> statement-breakpoint
create policy global_write on app_pages for all using (app_is_internal());--> statement-breakpoint
drop policy if exists global_read on app_page_roles;--> statement-breakpoint
create policy global_read on app_page_roles for select using (true);--> statement-breakpoint
drop policy if exists global_write on app_page_roles;--> statement-breakpoint
create policy global_write on app_page_roles for all using (app_is_internal());--> statement-breakpoint
grant select, insert, update, delete on app_pages to qvm_app;--> statement-breakpoint
grant select, insert, update, delete on app_page_roles to qvm_app;--> statement-breakpoint

